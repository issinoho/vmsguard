#!/usr/bin/env python3
"""Write the item tables the probes include.

Each entry has to sit under its own #ifdef, because the question every
probe asks first is whether the headers on that machine declare the
item at all, and the preprocessor cannot test inside a macro. Writing
two hundred of those by hand is how a typo gets in, so they are
generated. Run from this directory; the output is committed so that
nothing on OpenVMS needs Python.
"""

L, T, Q = "PK_LONG", "PK_TEXT", "PK_TIME"

TABLES = {
    "items_syi.h": ("syi_items", [
        ("SYI$_NODENAME", 15, T), ("SYI$_SCSNODE", 8, T),
        ("SYI$_VERSION", 8, T), ("SYI$_ARCH_NAME", 15, T),
        ("SYI$_HW_NAME", 64, T), ("SYI$_HW_MODEL", 4, L),
        ("SYI$_PAGE_SIZE", 4, L), ("SYI$_MEMSIZE", 4, L),
        ("SYI$_FREE_PAGES", 8, L),
        ("SYI$_ACTIVECPU_CNT", 4, L), ("SYI$_AVAILCPU_CNT", 4, L),
        ("SYI$_BOOTTIME", 8, Q),
        ("SYI$_CLUSTER_MEMBER", 4, L), ("SYI$_CLUSTER_NODES", 4, L),
        ("SYI$_PAGEFILE_PAGE", 4, L), ("SYI$_PAGEFILE_FREE", 4, L),
        ("SYI$_SWAPFILE_PAGE", 4, L), ("SYI$_SWAPFILE_FREE", 4, L),
        ("SYI$_MAXPROCESSCNT", 4, L),
    ]),
    # CPU modes first: probe_rmi.c sums the entries whose names start
    # with RMI$_CPU, and checks the total against wall time.
    "items_rmi.h": ("rmi_items", [
        ("RMI$_CPUINTSTK", 8, L), ("RMI$_CPUMPSYNCH", 8, L),
        ("RMI$_CPUKERNEL", 8, L), ("RMI$_CPUEXEC", 8, L),
        ("RMI$_CPUSUPER", 8, L), ("RMI$_CPUUSER", 8, L),
        ("RMI$_CPUCOMPAT", 8, L), ("RMI$_CPUIDLE", 8, L),
        ("RMI$_PROCS", 8, L),
        ("RMI$_FRLIST", 8, L), ("RMI$_MODLIST", 8, L),
        ("RMI$_FAULTS", 8, L), ("RMI$_PREADS", 8, L),
        ("RMI$_PWRITES", 8, L), ("RMI$_PREADIO", 8, L),
        ("RMI$_PWRITIO", 8, L), ("RMI$_SYSFAULTS", 8, L),
        ("RMI$_GVALFLTS", 8, L), ("RMI$_DZROFLTS", 8, L),
        ("RMI$_TRANSFLTS", 8, L), ("RMI$_ISWPCNT", 8, L),
        ("RMI$_DIRIO", 8, L), ("RMI$_BUFIO", 8, L),
        ("RMI$_MBREADS", 8, L), ("RMI$_MBWRITES", 8, L),
        ("RMI$_COM", 8, L), ("RMI$_COMO", 8, L), ("RMI$_CUR", 8, L),
        ("RMI$_PFW", 8, L), ("RMI$_LEF", 8, L), ("RMI$_LEFO", 8, L),
        ("RMI$_HIB", 8, L), ("RMI$_HIBO", 8, L), ("RMI$_SUSP", 8, L),
        ("RMI$_SUSPO", 8, L), ("RMI$_FPG", 8, L), ("RMI$_COLPG", 8, L),
        ("RMI$_MWAIT", 8, L), ("RMI$_CEF", 8, L),
    ]),
    "items_jpi.h": ("jpi_items", [
        ("JPI$_PID", 4, L), ("JPI$_PRCNAM", 15, T),
        ("JPI$_USERNAME", 12, T), ("JPI$_STATE", 4, L),
        ("JPI$_MODE", 4, L), ("JPI$_CPUTIM", 4, L),
        ("JPI$_PAGEFLTS", 4, L), ("JPI$_DIRIO", 4, L),
        ("JPI$_BUFIO", 4, L), ("JPI$_PPGCNT", 4, L),
        ("JPI$_GPGCNT", 4, L), ("JPI$_WSSIZE", 4, L),
        ("JPI$_VIRTPEAK", 4, L), ("JPI$_LOGINTIM", 8, Q),
        ("JPI$_IMAGNAME", 255, T),
    ]),
    "items_dvi.h": ("dvi_items", [
        ("DVI$_MNT", 4, L), ("DVI$_VOLNAM", 12, T),
        ("DVI$_LOGVOLNAM", 64, T), ("DVI$_MAXBLOCK", 4, L),
        ("DVI$_VOLSIZE", 4, L), ("DVI$_FREEBLOCKS", 4, L),
        ("DVI$_OPCNT", 4, L), ("DVI$_ERRCNT", 4, L),
        ("DVI$_SHDW_MASTER", 4, L), ("DVI$_SHDW_MEMBER", 4, L),
        ("DVI$_SHDW_MASTER_NAME", 64, T), ("DVI$_CLUSTER", 4, L),
    ]),
}

for fname, (var, items) in TABLES.items():
    out = ["/* Generated by gen_items.py -- edit that, not this. */", "",
           f"static const probe_item {var}[] = {{"]
    for name, size, kind in items:
        out += [f"#ifdef {name}",
                f"    PROBE_ITEM({name}, {size}, {kind}),",
                "#else",
                f"    PROBE_MISSING({name}, {size}, {kind}),",
                "#endif"]
    out += ["};", "",
            f"#define {var.upper()}_COUNT "
            f"(sizeof {var} / sizeof {var}[0])", ""]
    with open(fname, "w") as f:
        f.write("\n".join(out))
