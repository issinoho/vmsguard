#!/usr/bin/env python3
"""Write the stub item-code headers from the probes' own item tables.

The codes are arbitrary -- nothing here may depend on VMS's values --
and a few items are left out on purpose so the "not declared" branch
of each probe runs on Linux too. Run from this directory.
"""
import re

src = open("../probes/gen_items.py").read()
names = re.findall(r'\("((?:SYI|RMI|JPI|DVI)\$_[A-Z0-9_]+)"', src)
UNDECLARED = {"SYI$_FREE_PAGES", "RMI$_TRANSFLTS", "DVI$_VOLSIZE",
              "JPI$_VIRTPEAK"}
HDR = {"SYI": "syidef.h", "RMI": "rmidef.h", "JPI": "jpidef.h",
       "DVI": "dvidef.h"}

out = {h: [] for h in HDR.values()}
code = 100
for n in names:
    code += 1
    if n not in UNDECLARED:
        out[HDR[n[:3]]].append(f"#define {n} {code}")
for h, lines in out.items():
    guard = "STUB_" + h.replace(".", "_").upper()
    with open(h, "w") as f:
        f.write("/* Linux stub: codes are arbitrary, not VMS's. "
                "Generated by gen_stub_headers.py. */\n"
                f"#ifndef {guard}\n#define {guard}\n"
                + "\n".join(lines) + "\n#endif\n")
